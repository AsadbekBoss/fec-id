"""Encrypted local file storage (ARCHITECTURE §8).

Files are AES-256-GCM encrypted with a per-purpose subkey. The AAD binds each blob to its storage
key, so a file renamed or copied to another key fails to decrypt. Keys are generated by the
server and never come from user input (no path traversal). An S3-compatible backend can
implement the same interface later.
"""

from __future__ import annotations

import os
import re
import uuid
from pathlib import Path

import anyio

from app.core import crypto
from app.core.config import get_settings

_KEY_RE = re.compile(r"^[a-z_]+/[0-9a-f-]{36}/[0-9a-f-]{36}\.bin$")


class StorageError(Exception):
    pass


def new_key(category: str, owner_id: uuid.UUID) -> str:
    return f"{category}/{owner_id}/{uuid.uuid4()}.bin"


def _path(key: str) -> Path:
    if not _KEY_RE.fullmatch(key):
        raise StorageError("Invalid storage key")
    root = Path(get_settings().storage_dir).resolve()
    p = (root / key).resolve()
    if root not in p.parents:  # defence in depth; the regex already forbids ".."
        raise StorageError("Invalid storage key")
    return p


def _write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)  # atomic on the same filesystem


async def put(key: str, data: bytes, purpose: crypto.Purpose) -> None:
    blob = crypto.encrypt(data, purpose, f"storage:{key}")
    await anyio.to_thread.run_sync(_write, _path(key), blob)


async def get(key: str, purpose: crypto.Purpose) -> bytes:
    path = _path(key)
    try:
        blob = await anyio.to_thread.run_sync(path.read_bytes)
    except FileNotFoundError:
        raise StorageError("File not found") from None
    return crypto.decrypt(blob, purpose, f"storage:{key}")


async def delete(key: str | None) -> None:
    if not key:
        return
    path = _path(key)
    await anyio.to_thread.run_sync(lambda: path.unlink(missing_ok=True))
